"""Shared tutoring interaction rules; assessment still requires quoted evidence and sources."""
import re


def normalize_question_format(question: str) -> str:
    """Fix a wording mismatch without inventing or changing an exercise."""
    if "빈칸" in question and not re.search(r"_{2,}|□|\[\s*\]|\(\s*\)", question):
        return re.sub(r"빈칸에\s*알맞은\s*영어를\s*써\s*보세요", "질문에 영어로 답해 보세요", question)
    return question

